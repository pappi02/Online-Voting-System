"""
Management command to configure email settings interactively
Usage: python manage.py configure_email
"""

from django.core.management.base import BaseCommand
from pathlib import Path
import os


class Command(BaseCommand):
    help = 'Configure email settings interactively'

    def handle(self, *args, **options):
        self.stdout.write(self.style.MIGRATE_HEADING('\n=== Email Configuration Setup ===\n'))

        # Define config file path
        config_dir = Path(__file__).resolve().parent.parent.parent.parent / 'config'
        config_file = config_dir / '.env.email'

        # Check if config file exists
        if config_file.exists():
            self.stdout.write(self.style.WARNING(f'Configuration file already exists: {config_file}'))
            response = input('Do you want to overwrite it? (yes/no): ').strip().lower()
            if response not in ['yes', 'y']:
                self.stdout.write(self.style.WARNING('Configuration cancelled.'))
                return

        self.stdout.write(self.style.MIGRATE_LABEL('Select Email Provider:'))
        self.stdout.write('  1. Gmail (recommended for development)')
        self.stdout.write('  2. Outlook/Office 365')
        self.stdout.write('  3. SendGrid (recommended for production)')
        self.stdout.write('  4. Mailgun')
        self.stdout.write('  5. Custom SMTP')
        self.stdout.write('  6. Console (development only - no real emails)')

        provider_choice = input('\nEnter choice (1-6): ').strip()
        
        providers = {
            '1': 'gmail',
            '2': 'outlook',
            '3': 'sendgrid',
            '4': 'mailgun',
            '5': 'custom',
            '6': 'console'
        }

        provider = providers.get(provider_choice, 'console')
        
        # Collect configuration based on provider
        config_lines = [
            '# Email Configuration',
            '# Generated by configure_email management command',
            '',
            f'EMAIL_PROVIDER={provider}',
            ''
        ]

        if provider == 'console':
            config_lines.extend([
                '# Console Backend (Development Mode)',
                'EMAIL_DEVELOPMENT_MODE=True',
                '',
                'DEFAULT_FROM_EMAIL=noreply@ivotesystems.local',
                'SUPPORT_EMAIL=support@ivotesystems.local',
                'EMAIL_NOTIFICATION_ENABLED=True',
            ])
        else:
            is_dev = input('Is this for development? (yes/no): ').strip().lower() in ['yes', 'y']
            
            if provider == 'gmail':
                self.stdout.write('\n' + self.style.WARNING('Note: Gmail requires an App Password, not your regular password'))
                self.stdout.write('Generate one at: https://myaccount.google.com/apppasswords\n')
                
                email = input('Gmail address: ').strip()
                password = input('Gmail App Password: ').strip()
                
                config_lines.extend([
                    f'# Gmail Configuration',
                    f'GMAIL_EMAIL_HOST=smtp.gmail.com',
                    f'GMAIL_EMAIL_PORT=587',
                    f'GMAIL_EMAIL_USE_TLS=True',
                    f'GMAIL_EMAIL_HOST_USER={email}',
                    f'GMAIL_EMAIL_HOST_PASSWORD={password}',
                ])
            
            elif provider == 'outlook':
                email = input('Outlook email address: ').strip()
                password = input('Outlook password: ').strip()
                
                config_lines.extend([
                    f'# Outlook Configuration',
                    f'OUTLOOK_EMAIL_HOST=smtp-mail.outlook.com',
                    f'OUTLOOK_EMAIL_PORT=587',
                    f'OUTLOOK_EMAIL_USE_TLS=True',
                    f'OUTLOOK_EMAIL_HOST_USER={email}',
                    f'OUTLOOK_EMAIL_HOST_PASSWORD={password}',
                ])
            
            elif provider == 'sendgrid':
                self.stdout.write('\n' + self.style.WARNING('Note: Use your SendGrid API key as the password'))
                api_key = input('SendGrid API Key: ').strip()
                
                config_lines.extend([
                    f'# SendGrid Configuration',
                    f'SENDGRID_EMAIL_HOST=smtp.sendgrid.net',
                    f'SENDGRID_EMAIL_PORT=587',
                    f'SENDGRID_EMAIL_USE_TLS=True',
                    f'SENDGRID_EMAIL_HOST_USER=apikey',
                    f'SENDGRID_EMAIL_HOST_PASSWORD={api_key}',
                ])
            
            elif provider == 'mailgun':
                host_user = input('Mailgun username (e.g., postmaster@yourdomain.mailgun.org): ').strip()
                password = input('Mailgun password: ').strip()
                
                config_lines.extend([
                    f'# Mailgun Configuration',
                    f'MAILGUN_EMAIL_HOST=smtp.mailgun.org',
                    f'MAILGUN_EMAIL_PORT=587',
                    f'MAILGUN_EMAIL_USE_TLS=True',
                    f'MAILGUN_EMAIL_HOST_USER={host_user}',
                    f'MAILGUN_EMAIL_HOST_PASSWORD={password}',
                ])
            
            else:  # custom
                host = input('SMTP Host: ').strip()
                port = input('SMTP Port (default 587): ').strip() or '587'
                use_tls = input('Use TLS? (yes/no, default yes): ').strip().lower() not in ['no', 'n']
                user = input('SMTP Username: ').strip()
                password = input('SMTP Password: ').strip()
                
                config_lines.extend([
                    f'# Custom SMTP Configuration',
                    f'CUSTOM_EMAIL_HOST={host}',
                    f'CUSTOM_EMAIL_PORT={port}',
                    f'CUSTOM_EMAIL_USE_TLS={use_tls}',
                    f'CUSTOM_EMAIL_HOST_USER={user}',
                    f'CUSTOM_EMAIL_HOST_PASSWORD={password}',
                ])
            
            # Common settings
            from_email = input('\nFrom Email (e.g., noreply@ivotesystems.com): ').strip()
            support_email = input('Support Email (e.g., support@ivotesystems.com): ').strip()
            
            config_lines.extend([
                '',
                '# Email Addresses',
                f'DEFAULT_FROM_EMAIL={from_email or "noreply@ivotesystems.com"}',
                f'SUPPORT_EMAIL={support_email or "support@ivotesystems.com"}',
                '',
                '# Email Features',
                f'EMAIL_DEVELOPMENT_MODE={str(is_dev)}',
                'EMAIL_NOTIFICATION_ENABLED=True',
                'EMAIL_VERIFICATION_REQUIRED=True',
                'EMAIL_VERIFICATION_DEADLINE_DAYS=14',
                'EMAIL_REMINDER_DAYS_BEFORE=7',
            ])

        # Write configuration file
        try:
            config_dir.mkdir(parents=True, exist_ok=True)
            with open(config_file, 'w') as f:
                f.write('\n'.join(config_lines))
            
            self.stdout.write('\n' + self.style.SUCCESS(f'✓ Configuration saved to: {config_file}'))
            self.stdout.write('\n' + self.style.MIGRATE_LABEL('Next Steps:'))
            self.stdout.write('  1. Test your configuration:')
            self.stdout.write('     python manage.py test_email your-email@example.com')
            self.stdout.write('  2. Restart your Django server to apply changes')
            self.stdout.write('\n' + self.style.SUCCESS('=== Configuration Complete ===\n'))
            
        except Exception as e:
            self.stdout.write(self.style.ERROR(f'\n✗ Failed to save configuration: {str(e)}'))
